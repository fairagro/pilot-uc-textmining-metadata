import os
import json
import argparse
import requests

from datasets import load_dataset

from code.Experiments.evaluation import evaluate_all, extract_prediction_json
from code.Experiments.generate_ner_prompt import generate_ner_prompts


HF_DATASET = (
    "IT-ZBMED/"
    "Agriculture_NER_Dataset_for_FAIR_Metadata_Enrichment"
)

DATASET_CONFIG = "doc_split"

# Step 1: Perform NER with GPT-5 through OpenRouter
def perform_ner(text, max_length=1512):
    system_prompt, user_prompt = generate_ner_prompts(text)

    response = requests.post(
        url="https://openrouter.ai/api/v1/chat/completions",
        headers={
            "Authorization": f"Bearer {os.environ['OPENROUTER_API_KEY']}",
            "Content-Type": "application/json"
        },
        data=json.dumps({
            "model": "openai/gpt-5",
            "messages": [
                {
                    "role": "system",
                    "content": system_prompt
                },
                {
                    "role": "user",
                    "content": user_prompt
                }
            ],
            "provider": {
                "sort": "price"
            },
            "temperature": 0.7,
            "max_tokens": max_length,
            "top_p": 0.90
        })
    )

    response.raise_for_status()

    return response.json()


# Step 2: Process Multiple Text Files
def process_text_files(test_dataset, output_dir, max_length):
    """
    Process the Hugging Face TEST split.

    Parameters
    ----------
    test_dataset :
        Hugging Face test split.
    output_dir : str
        Directory where the annotated files are saved.
    max_length : int
        Maximum number of output tokens generated by the model.
    """

    os.makedirs(
        output_dir,
        exist_ok=True
    )

    print(
        f"Processing {len(test_dataset)} "
        "test documents..."
    )

    for example in test_dataset:

        filename = example["file_name"]

        # Reconstruct the full document from the token list
        text = " ".join(example["Tokens"])

        output_text_path = os.path.join(
            output_dir,
            filename.replace(
                ".txt",
                "_annotated.txt"
            )
        )

        if os.path.exists(output_text_path):
            prediction = extract_prediction_json(
                output_text_path
            )

            if prediction is not None:
                print(
                    f"Skipping {filename} "
                    "(already processed)."
                )
                continue

            print(
                f"Existing result for {filename} "
                "is invalid. Reprocessing..."
            )

        print(f"Processing {filename}...")

        ner_result = perform_ner(
            text,
            max_length
        )

        with open(
            output_text_path,
            "w",
            encoding="utf-8"
        ) as file:
            json.dump(
                ner_result,
                file,
                ensure_ascii=False,
                indent=2
            )

        print(
            f"NER results saved to {output_text_path}"
        )


# Step 3: Main Execution
if __name__ == "__main__":

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--dataset_name",
        default=HF_DATASET,
        help="Hugging Face dataset repository."
    )

    parser.add_argument(
        "--dataset_config",
        default=DATASET_CONFIG,
        help="Hugging Face dataset configuration."
    )

    parser.add_argument(
        "--output_dir",
        default=(
            "Code/Experiments/"
            "filtered_df_soil_crop_year_LTE_test_annotated_GPT5"
        ),
        help="Directory for raw LLM outputs."
    )

    parser.add_argument(
        "--output_dir_json",
        default="Code/Experiments/results/zero_shot_gpt5",
        help="Directory for evaluation metrics."
    )

    parser.add_argument(
        "--model_name",
        default="GPT-5",
        help="Human-readable model name used in evaluation results."
    )

    parser.add_argument(
        "--max_length",
        type=int,
        default=1512,
        help="Maximum number of output tokens."
    )

    args = parser.parse_args()

    dataset = load_dataset(
        args.dataset_name,
        args.dataset_config
    )

    test_dataset = dataset["test"]

    process_text_files(
        test_dataset,
        args.output_dir,
        args.max_length
    )

    log_dir = os.environ.get(
        "LOG_DIR"
    )

    evaluate_all(
        args.model_name,
        test_dataset,
        args.output_dir,
        args.output_dir_json,
        None,
        log_dir
    )

    print("NER processing complete.")
